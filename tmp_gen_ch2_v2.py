def compute_mbti_v6(d):
    theta=float(d['theta']); hA=float(d['highAlpha']); lA=float(d['lowAlpha'])
    lB=float(d['lowBeta']); hB=float(d['highBeta']); hG=float(d['highGamma'])
    lG=float(d['lowGamma']); fo=float(d['focus']); re=float(d['relaxation'])
    eid=fo*.35+hG*.35+hB*.30-(hA*.40+re*.30+lA*.30)
    nsd=theta*.60+hA*.40-(lB*.55+hG*.45)
    tfd=((lB+hB)/2)-(lG*.55+hA*.45)
    jpd=hB*.45+fo*.55-(theta*.50+re*.50)
    ei='E' if eid>0 else 'I'; ns='N' if nsd>8 else 'S'
    tf='T' if tfd>0 else 'F'; jp='J' if jpd>0 else 'P'
    mt=ei+ns+tf+jp
    cl=lambda v:max(5,min(99,round(v)))
    cl78=lambda v:max(10,min(78,round(v)))
    EI=cl(50+eid*.6); NS=cl(50+(nsd-8)*.6); TF=cl(50+tfd*.6); JP=cl(50+jpd*.6)
    bd=sorted([('EI',abs(eid),0,'I' if ei=='E' else 'E'),
               ('NS',abs(nsd-8),1,'S' if ns=='N' else 'N'),
               ('TF',abs(tfd),2,'F' if tf=='T' else 'T'),
               ('JP',abs(jpd),3,'P' if jp=='J' else 'J')],key=lambda x:x[1])
    sec=[]
    for ax,df,pos,fl in bd[:2]:
        st=cl78(78-df*1.8)
        if st<20: break
        t=list(mt); t[pos]=fl
        sec.append({'mbti':''.join(t),'strength':st,'axis':ax,'diff':round(df,1)})
    return {'mbti':mt,'EI':EI,'NS':NS,'TF':TF,'JP':JP,
            'eiDiff':round(eid,1),'nsDiff':round(nsd,1),'tfDiff':round(tfd,1),'jpDiff':round(jpd,1),
            'secondaries':sec}

