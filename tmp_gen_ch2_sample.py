# ─── v6.0 算法（純 Python，和後端完全一致）──────────────────────────────────

def compute_mbti_v6(d: dict) -> dict:
    theta      = float(d.get('theta', 50))
    highAlpha  = float(d.get('highAlpha', 50))
    lowAlpha   = float(d.get('lowAlpha', 50))
    lowBeta    = float(d.get('lowBeta', 50))
    highBeta   = float(d.get('highBeta', 50))
    highGamma  = float(d.get('highGamma', 50))
    lowGamma   = float(d.get('lowGamma', 50))
    focus      = float(d.get('focus', 50))
    relaxation = float(d.get('relaxation', 50))

    E_score = focus*0.35 + highGamma*0.35 + highBeta*0.30
    I_score = highAlpha*0.40 + relaxation*0.30 + lowAlpha*0.30
    eiDiff  = E_score - I_score

    N_score = theta*0.60 + highAlpha*0.40
    S_score = lowBeta*0.55 + highGamma*0.45
    nsDiff  = N_score - S_score

    T_score = lowBeta*0.50 + highBeta*0.50
    F_score = lowGamma*0.55 + highAlpha*0.45
    tfDiff  = T_score - F_score

    J_score = highBeta*0.45 + focus*0.55
    P_score = theta*0.50 + relaxation*0.50
    jpDiff  = J_score - P_score

    ei = 'E' if eiDiff > 0 else 'I'
    ns = 'N' if nsDiff > 8 else 'S'
    tf = 'T' if tfDiff > 0 else 'F'
    jp = 'J' if jpDiff > 0 else 'P'
    mbti = ei + ns + tf + jp

    def clamp(v): return max(5, min(99, round(v)))
    def clamp78(v): return max(10, min(78, round(v)))

    EI = clamp(50 + eiDiff * 0.6)
    NS = clamp(50 + (nsDiff - 8) * 0.6)
    TF = clamp(50 + tfDiff * 0.6)
    JP = clamp(50 + jpDiff * 0.6)

    borders = [
        {'axis':'EI','diff':abs(eiDiff),     'pos':0,'flip':'I' if ei=='E' else 'E'},
        {'axis':'NS','diff':abs(nsDiff-8),    'pos':1,'flip':'S' if ns=='N' else 'N'},
        {'axis':'TF','diff':abs(tfDiff),      'pos':2,'flip':'F' if tf=='T' else 'T'},
        {'axis':'JP','diff':abs(jpDiff),      'pos':3,'flip':'P' if jp=='J' else 'J'},
    ]
    borders.sort(key=lambda x: x['diff'])
    
    secondaries = []
    for b in borders[:2]:
        st = clamp78(78 - b['diff'] * 1.8)
        if st < 20: break
        sec = list(mbti); sec[b['pos']] = b['flip']
        secondaries.append({'mbti':''.join(sec),'strength':st,'axis':b['axis'],
                             'diff':round(b['diff'],1)})

    return {'mbti':mbti,'EI':EI,'NS':NS,'TF':TF,'JP':JP,
            'eiDiff':round(eiDiff,1),'nsDiff':round(nsDiff,1),
            'tfDiff':round(tfDiff,1),'jpDiff':round(jpDiff,1),
            'secondaries':secondaries}

