    print(f"           β↓={data['lowBeta']} β↑={data['highBeta']} γ↑={data['highGamma']}")
    print(f"           γ↓={data['lowGamma']} focus={data['focus']} relax={data['relaxation']}")
    print()
    print(f"  主性格：{r['mbti']}（{MBTI_ZH.get(r['mbti'],'未知')}）")
    print()
    print(f"  四軸分數（50=中立）：")
    print(f"    EI={r['EI']:2d} ({'E外向激活' if r['EI']>50 else 'I內部充電'}) | diff={r['eiDiff']:+.1f}")
    print(f"    NS={r['NS']:2d} ({'N直覺跳躍' if r['NS']>50 else 'S感知細節'}) | diff={r['nsDiff']:+.1f}（N需>+8）")
    print(f"    TF={r['TF']:2d} ({'T邏輯優先' if r['TF']>50 else 'F共情優先'}) | diff={r['tfDiff']:+.1f}")
    print(f"    JP={r['JP']:2d} ({'J執行導向' if r['JP']>50 else 'P探索導向'}) | diff={r['jpDiff']:+.1f}")
    print()
    
    # 邊界距排序
    borders = [
        ('EI', abs(r['eiDiff'])),
        ('NS', abs(r['nsDiff']-8)),
        ('TF', abs(r['tfDiff'])),
        ('JP', abs(r['jpDiff'])),
    ]
    borders.sort(key=lambda x: x[1])
    print(f"  邊界距（越小=矛盾越強）：")
    for ax, d in borders:
        bar = '█' * int(d/3)
        print(f"    {ax}: {d:5.1f}  {bar}")
    print()
    
    if r['secondaries']:
        print(f"  次性格：")
        for s in r['secondaries']:
            zh = MBTI_ZH.get(s['mbti'],'未知')
            level = '非常強（日常自然浮現）' if s['strength']>=60 else \
                    '中等（特定情境觸發）' if s['strength']>=40 else \
                    '弱（壓力或極端情境）'
            print(f"    {s['mbti']}（{zh}）強度 {s['strength']}% — {level}")
            print(f"    成因：{s['axis']}軸最接近翻轉（邊界距 {s['diff']}），主性格翻轉此軸得到次性格")
    else:
        print(f"  次性格：無（各軸分數均遠離邊界，性格穩定）")
    
    print()
    # 壓力態分析
    stability = data['lowAlpha'] / max(data['highBeta'], 1)
    tension = data['highBeta'] - data['lowAlpha']
    print(f"  壓力分析：")
    print(f"    成熟穩定指數 = α↓/β↑ = {data['lowAlpha']}/{data['highBeta']} = {stability:.2f}")
    print(f"    壓力張力 = β↑-α↓ = {tension}")
    if stability >= 1.0:
        print(f"    → 穩定型（很少進入壓力態）")
    elif stability >= 0.7:
        print(f"    → 中度型（在高壓下有時會進入壓力態）")
    else:
        print(f"    → 壓力敏感型（較容易切換到陰影性格）")
    
    # 陰影性格 = 邊界距最小的軸翻轉
    weakest = borders[0][0]
    shadow = list(r['mbti'])
    axis_pos = {'EI':0,'NS':1,'TF':2,'JP':3}
    axis_flip = {'E':'I','I':'E','N':'S','S':'N','T':'F','F':'T','J':'P','P':'J'}
    pos = axis_pos[weakest]
    shadow[pos] = axis_flip[shadow[pos]]
    shadow_type = ''.join(shadow)
    print(f"    壓力態陰影性格：{shadow_type}（{MBTI_ZH.get(shadow_type,'未知')}）← {weakest}軸翻轉")
    print()

